/** Column widths for an 8 → 12 pop. Sum is 12. */
export const POP_COL = [2, 1, 2, 1, 2, 1, 2, 1] as const
/** Row heights for a 10 → 15 pop. Sum is 15. */
export const POP_ROW = [2, 1, 2, 1, 2, 1, 2, 1, 2, 1] as const

export function glyphBit(digit: number, x: number, y: number): boolean {
  const row = GLYPHS[digit]?.[y]
  if (row === undefined) return false
  if (x < 0 || x >= GLYPH_W || y < 0 || y >= GLYPH_H) return false
  return (row & (1 << (GLYPH_W - 1 - x))) !== 0
}
